"""Phase 4 Challenge Evaluation Pilot runner.

Executes the 24 Phase 4 challenge cases through three architecture
configurations (C0 bare_baseline / C1 all_on / C2 no_memory) using the
frozen evaluation runner (:func:`evals.runner.run_evaluation`), then
persists one raw output file per (arm, case) under
``data/evaluation/challenge_raw/<arm>/<case_id>.json``.

Decoupling contract:
- This script consumes only the public runner API and writes its own files;
  it never imports agent internals and never mutates system modules.
- The runner is imported lazily (same pattern as
  :mod:`experiments.runner_adapter`) so importing this script stays light
  and tests can substitute a fake runner via ``evals.runner.run_evaluation``.

Usage from the repo root::

    python scripts/run_challenge_evaluation.py --seed 42
    python scripts/run_challenge_evaluation.py --arms c0_bare_baseline
    python scripts/run_challenge_evaluation.py --max-cases 3 --force
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from evals.config import EvalConfig
from utils.judge_runtime import resolve_judge_config

#: Challenge set source (Phase 4, frozen).
CHALLENGE_PATH = ROOT / "benchmarks" / "challenge_set_v1.json"

#: Default raw-output root.
DEFAULT_RAW_DIR = ROOT / "data" / "evaluation" / "challenge_raw"

#: Flattened dataset name served to the runner.
FLATTENED_DATASET_NAME = "challenge_set_v1_flattened.json"


@dataclass(frozen=True)
class ChallengeArm:
    """One architecture configuration for the pilot."""

    name: str
    label: str
    description: str
    planner_on: bool
    debate_on: bool
    critic_on: bool
    memory_on: bool
    tool_router_on: bool
    counterfactual_on: bool


#: The three pilot arms (Phase 4 Evaluation Pilot spec).
CHALLENGE_ARMS: dict[str, ChallengeArm] = {
    "c0_bare_baseline": ChallengeArm(
        name="c0_bare_baseline",
        label="C0 (Baseline)",
        description="bare_baseline：无记忆、无规划、无辩论、无反思",
        planner_on=False,
        debate_on=False,
        critic_on=False,
        memory_on=False,
        tool_router_on=False,
        counterfactual_on=False,
    ),
    "c1_all_on": ChallengeArm(
        name="c1_all_on",
        label="C1 (Full)",
        description="all_on：完整多 Agent 链路",
        planner_on=True,
        debate_on=True,
        critic_on=True,
        memory_on=True,
        tool_router_on=True,
        counterfactual_on=True,
    ),
    "c2_no_memory": ChallengeArm(
        name="c2_no_memory",
        label="C2 (Critical Ablation)",
        description="no_memory：关闭 RAG/KG/案例记忆，其余开启",
        planner_on=True,
        debate_on=True,
        critic_on=True,
        memory_on=False,
        tool_router_on=True,
        counterfactual_on=True,
    ),
}


def flatten_challenge_set(data: dict[str, Any]) -> list[dict[str, Any]]:
    """Flatten the grouped challenge set into a flat case list.

    Each case keeps its metadata (group, difficulty, expected_key_factors,
    ground_truth, crop, intent) plus ``query``/``id`` so it satisfies the
    runner's ``EvalCase`` contract.
    """
    cases: list[dict[str, Any]] = []
    for spec in data.get("groups", {}).values():
        for case in spec.get("cases", []):
            flat = {
                "id": case["id"],
                "query": case["input"],
                "group": case["group"],
                "difficulty": case["difficulty"],
                "expected_key_factors": list(case["expected_key_factors"]),
                "ground_truth": case.get("ground_truth"),
                "crop": case.get("crop"),
                "intent": case.get("intent"),
                "design_intent": case.get("design_intent"),
            }
            cases.append(flat)
    return cases


def load_challenge_set() -> list[dict[str, Any]]:
    """Load and flatten ``benchmarks/challenge_set_v1.json``."""
    data = json.loads(CHALLENGE_PATH.read_text(encoding="utf-8"))
    return flatten_challenge_set(data)


def write_flattened_dataset(cases: list[dict[str, Any]], path: Path) -> Path:
    """Persist the flattened dataset in the runner's ``{"cases": [...]}``
    JSON contract."""
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "name": "challenge_set_v1_flattened",
        "description": "Phase 4 Challenge Set flattened for the evaluation "
        "runner (generated by scripts/run_challenge_evaluation.py)",
        "cases": cases,
    }
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return path


def _judge_payload(trace: dict[str, Any]) -> dict[str, Any]:
    events = trace.get("judge") or []
    return events[0] if events else {}


def run_arm(
    arm: ChallengeArm,
    cases: list[dict[str, Any]],
    output_dir: Path,
    *,
    seed: int = 42,
    max_cases: int | None = None,
    use_langgraph: bool = True,
    use_llm_judge: bool = True,
    force: bool = False,
) -> Path:
    """Run one arm over the challenge cases and write per-case raw outputs.

    The runner (and its heavy dependency stack) is imported lazily so that
    tests can run this function against a fake
    ``evals.runner.run_evaluation`` without loading the orchestrator.
    """
    arm_dir = output_dir / arm.name
    selected = cases if max_cases is None else cases[:max_cases]
    if not force and _arm_complete(arm_dir, selected):
        print(f"  [skip] {arm.name}: {len(selected)} raw outputs already "
              "present (use --force to rerun)")
        return arm_dir

    from evals.runner import run_evaluation

    flattened = write_flattened_dataset(
        cases, output_dir / "_flattened" / FLATTENED_DATASET_NAME
    )
    config = EvalConfig(
        dataset=str(flattened),
        output_dir=str(arm_dir / "runner"),
        save_traces=True,
        use_langgraph=use_langgraph,
        use_llm_judge=use_llm_judge,
        seed=seed,
        max_cases=max_cases,
    )
    started = datetime.now(timezone.utc).isoformat()
    result = run_evaluation(config)
    finished = datetime.now(timezone.utc).isoformat()

    trace_dir = result.trace_dir
    if trace_dir is None:
        raise RuntimeError(f"arm {arm.name}: runner produced no trace dir")
    case_by_id = {case["id"]: case for case in cases}
    arm_dir.mkdir(parents=True, exist_ok=True)
    written = 0
    for row in result.rows:
        case = case_by_id[row.case_id]
        trace_path = trace_dir / f"{row.trace_id}.json"
        trace = (
            json.loads(trace_path.read_text(encoding="utf-8"))
            if trace_path.exists()
            else {}
        )
        judge = _judge_payload(trace)
        judge_confidence: Any = judge.get("confidence")
        if judge_confidence is None:
            judge_confidence = row.confidence
        payload = {
            "arm": arm.name,
            "arm_label": arm.label,
            "case_id": row.case_id,
            "group": case.get("group"),
            "difficulty": case.get("difficulty"),
            "input": case.get("input"),
            "expected_key_factors": case.get("expected_key_factors"),
            "ground_truth": case.get("ground_truth"),
            "crop": case.get("crop"),
            "intent": case.get("intent"),
            "trace_id": row.trace_id,
            "decision": str(judge.get("decision") or row.decision),
            "confidence": float(judge_confidence),
            "judge_mode": judge.get("judge_mode", "rules"),
            "judge_runtime": (
                judge.get("judge_analysis", {}).get("judge_runtime", {})
            ),
            "reasoning_trace": judge.get("reasoning_trace", ""),
            "summary": judge.get("summary", ""),
            "action_plan": judge.get("action_plan", []),
            "runtime_seconds": row.runtime_seconds,
            "trace": trace,
        }
        raw_path = arm_dir / f"{row.case_id}.json"
        raw_path.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        written += 1

    runtime = resolve_judge_config()
    manifest = {
        "arm": arm.name,
        "label": arm.label,
        "description": arm.description,
        "seed": seed,
        "cases": written,
        "max_cases": max_cases,
        "use_langgraph": use_langgraph,
        "use_llm_judge": use_llm_judge,
        "judge_model": _judge_model(),
        "judge_runtime_config": runtime.public_metadata(),
        "execution_semantics": "acis_real_agent",
        "decision_semantics": "final_judge_decision",
        "confidence_semantics": (
            "Judge confidence that the final decision label is correct"
        ),
        "started": started,
        "finished": finished,
    }
    (arm_dir / "run_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"  [done] {arm.name}: {written} raw outputs -> {arm_dir}")
    return arm_dir


def _arm_complete(arm_dir: Path, cases: list[dict[str, Any]]) -> bool:
    return all((arm_dir / f"{case['id']}.json").exists() for case in cases)


def _judge_model() -> str:
    return resolve_judge_config().model


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Phase 4 Challenge Evaluation Pilot runner"
    )
    parser.add_argument(
        "--output-dir",
        default=str(DEFAULT_RAW_DIR),
        help=f"raw output root (default: {DEFAULT_RAW_DIR})",
    )
    parser.add_argument(
        "--arms",
        nargs="*",
        choices=tuple(CHALLENGE_ARMS),
        default=tuple(CHALLENGE_ARMS),
        help="arms to run (default: all three)",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--max-cases",
        type=int,
        default=None,
        help="limit cases per arm (for smoke runs)",
    )
    parser.add_argument(
        "--llm-judge",
        action="store_true",
        default=True,
        help="use the LLM judge for decisions (default; "
        "falls back to rules per case on API failure)",
    )
    parser.add_argument(
        "--rules-only",
        action="store_true",
        help="use the rules orchestration path and the rule judge",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="rerun arms even when raw outputs already exist",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    cases = load_challenge_set()
    if not cases:
        print(f"error: no cases found in {CHALLENGE_PATH}")
        return 1
    use_langgraph = not args.rules_only
    use_llm_judge = args.llm_judge and not args.rules_only
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"[pilot] {len(cases)} challenge cases, seed={args.seed}")
    for name in args.arms:
        arm = CHALLENGE_ARMS[name]
        print(f"[arm] {arm.label} ({arm.name}) — {arm.description}")
        run_arm(
            arm,
            cases,
            output_dir,
            seed=args.seed,
            max_cases=args.max_cases,
            use_langgraph=use_langgraph,
            use_llm_judge=use_llm_judge,
            force=args.force,
        )

    runtime = resolve_judge_config()
    root_manifest = {
        "challenge_set": str(CHALLENGE_PATH),
        "challenge_set_version": "v1",
        "total_cases": len(cases),
        "arms": list(args.arms),
        "seed": args.seed,
        "use_langgraph": use_langgraph,
        "use_llm_judge": use_llm_judge,
        "judge_runtime_config": runtime.public_metadata(),
        "execution_semantics": "acis_real_agent",
        "decision_semantics": "final_judge_decision",
        "confidence_semantics": (
            "Judge confidence that the final decision label is correct"
        ),
        "created": datetime.now(timezone.utc).isoformat(),
    }
    (output_dir / "run_manifest.json").write_text(
        json.dumps(root_manifest, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"[pilot] manifest -> {output_dir / 'run_manifest.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
